export function make<K extends CollectionKey>(key: K, patch: Partial<Collections[K]> = {}): Collections[K] {
  return { ...defaults[key](), ...patch } as Collections[K];
}

export function emptyWorkspaceData(name: string): WorkspaceData {
  const t = nowIso();
  return {
    version: 1,
    workspace: {
      id: uid(),
      name,
      statusLabels: { ...DEFAULT_STATUS_LABELS },
      mapAutoLayout: true,
      createdAt: t,
      updatedAt: t,
    },
    products: {},
    categories: {},
    nodes: {},
    edges: {},
    content: {},
    initiatives: {},
    research: {},
    tasks: {},
    characters: {},
    arcs: {},
    issues: {},
    lore: {},
    links: {},
    activity: [],
  };
}
