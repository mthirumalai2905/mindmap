import { createClient, type RealtimeChannel, type SupabaseClient } from "@supabase/supabase-js";
import { parseSnapshot } from "../schemas";
import { COLLECTION_KEYS, type ActivityEntry, type CollectionKey, type Workspace, type WorkspaceData } from "../types";
import type { PersistenceAdapter, RemoteChange } from "./adapter";

export const TABLES: Record<CollectionKey, string> = {
  products: "products",
  categories: "categories",
  nodes: "map_nodes",
  edges: "map_edges",
  content: "content_items",
  initiatives: "initiatives",
  research: "research_ideas",
  tasks: "tasks",
  characters: "characters",
  arcs: "story_arcs",
  issues: "comic_issues",
  lore: "lore_entries",
  links: "relationships",
};
const COLLECTION_BY_TABLE = Object.fromEntries(Object.entries(TABLES).map(([k, t]) => [t, k as CollectionKey]));


const snake = (s: string) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const camel = (s: string) => s.replace(/_([a-z])/g, (_, c: string) => c.toUpperCase());
const isDateKey = (k: string) => /Date$/.test(k);
const isTimestampKey = (k: string) => k === "createdAt" || k === "updatedAt" || k === "at";

function toRow(record: object, workspaceId: string) {
  const row: Record<string, unknown> = { workspace_id: workspaceId };
  if ("createdAt" in record) row.is_example = Boolean((record as { isExample?: boolean }).isExample);
  for (const [k, v] of Object.entries(record)) {
    if (v === undefined) continue;
    row[snake(k)] = isDateKey(k) && v === "" ? null : v;
  }
  return row;
}

function workspaceRow(ws: Workspace) {
  const row = toRow(ws, ws.id);
  delete row.workspace_id;
  delete row.is_example;
  // Generated by the database; never overwritten by clients.
  delete row.join_code;
  delete row.created_by;
  return row;
}

function fromRow(row: Record<string, unknown>) {
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(row)) {
    if (k === "workspace_id") continue;
    const key = camel(k);
    if (isDateKey(key)) out[key] = v ?? "";
    else if (isTimestampKey(key) && typeof v === "string") out[key] = new Date(v).toISOString();
    else out[key] = v;
  }
  return out;
}

let client: SupabaseClient | null = null;
export function getSupabase(): SupabaseClient {
  if (!client) {
    client = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL!, process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!, {
      auth: { persistSession: false, autoRefreshToken: false, detectSessionInUrl: false },
    });
  }
  return client;
}

/**
 * Supabase persistence with last-write-wins sync.
 *
 * Saves upsert every changed row in full and delete removed rows. Realtime
 * pushes other members' writes to `onRemoteChange` listeners; the store applies
 * them unless its own copy of that record is newer. When the tab regains focus
 * the full workspace is re-read to catch anything missed while disconnected.
 *
 * There is no sign-in: requests use the publishable key and the open
 * row-level-security policies from migration 0002.
 */
export function createSupabaseAdapter(): PersistenceAdapter {
  const sb = getSupabase();
  let workspaceId: string | null = null;
  let channel: RealtimeChannel | null = null;
  const listeners = new Set<(c: RemoteChange) => void>();
  const emit = (c: RemoteChange) => listeners.forEach((l) => l(c));

  const check = (error: { message: string } | null, context: string) => {
    if (error) throw new Error(`${context}: ${error.message}`);
  };

  const readWorkspace = async (wid: string): Promise<WorkspaceData> => {
    const { data: ws, error: wErr } = await sb.from("workspaces").select("*").eq("id", wid).single();
    check(wErr, "Loading workspace");
    const snapshot: Record<string, unknown> = { version: 1, workspace: fromRow(ws as Record<string, unknown>) };
    await Promise.all(
      COLLECTION_KEYS.map(async (key) => {
        const rows: Record<string, unknown>[] = [];
        // PostgREST caps responses; page through large collections.
        for (let from = 0; ; from += 1000) {
          const { data, error } = await sb.from(TABLES[key]).select("*").eq("workspace_id", wid).range(from, from + 999);
          check(error, `Loading ${key}`);
          rows.push(...(data ?? []));
          if (!data || data.length < 1000) break;
        }
        snapshot[key] = Object.fromEntries(rows.map((r) => [r.id as string, fromRow(r)]));
      }),
    );
    const { data: activity, error: aErr } = await sb
      .from("activity_log")
      .select("*")
      .eq("workspace_id", wid)
      .order("at", { ascending: false })
      .limit(200);
    check(aErr, "Loading activity");
    snapshot.activity = (activity ?? []).map(fromRow).reverse();
    const parsed = parseSnapshot(snapshot);
    if (!parsed.ok) throw new Error(parsed.error);
    return parsed.data;
  };

  const subscribe = (wid: string) => {
    if (channel) void sb.removeChannel(channel);
    // Unique per subscription: channel names are shared across the client.
    let ch = sb.channel(`workspace:${wid}:${Math.random().toString(36).slice(2)}`);
    for (const table of Object.values(TABLES)) {
      ch = ch.on("postgres_changes", { event: "*", schema: "public", table, filter: `workspace_id=eq.${wid}` }, (payload) => {
        const collection = COLLECTION_BY_TABLE[table];
        if (payload.eventType === "DELETE") {
          const id = (payload.old as { id?: string }).id;
          if (id) emit({ kind: "delete", collection, id });
        } else {
          emit({ kind: "upsert", collection, record: fromRow(payload.new) as { id: string; updatedAt: string } });
        }
      });
    }
    ch = ch
      .on("postgres_changes", { event: "UPDATE", schema: "public", table: "workspaces", filter: `id=eq.${wid}` }, (payload) =>
        emit({ kind: "workspace", workspace: fromRow(payload.new) as unknown as Workspace }),
      )
      .on("postgres_changes", { event: "INSERT", schema: "public", table: "activity_log", filter: `workspace_id=eq.${wid}` }, (payload) =>
        emit({ kind: "activity", entry: fromRow(payload.new) as unknown as ActivityEntry }),
      );
    let subscribedOnce = false;
    channel = ch.subscribe((status) => {
      // After a reconnect, re-read everything so missed changes are applied.
      if (status === "SUBSCRIBED") {
        if (subscribedOnce) void catchUp();
        subscribedOnce = true;
      }
    });
  };

  let lastCatchUp = Date.now();
  const catchUp = async () => {
    if (!workspaceId) return;
    lastCatchUp = Date.now();
    try {
      emit({ kind: "snapshot", data: await readWorkspace(workspaceId) });
    } catch {
      // Offline or signed out; the next focus or reconnect retries.
    }
  };

  if (typeof window !== "undefined") {
    window.addEventListener("focus", () => {
      if (Date.now() - lastCatchUp > 15_000) void catchUp();
    });
  }

  const adapter: PersistenceAdapter = {
    mode: "supabase",
    description: "Shared workspace synced to Supabase. No sign-in: anyone with the app link can read and write. The latest save of a record wins.",

    async load() {
      // One shared workspace: the most recently created one.
      const { data: rows, error } = await sb.from("workspaces").select("id").order("created_at", { ascending: false }).limit(1);
      check(error, "Finding workspace");
      if (!rows?.length) return null;
      workspaceId = rows[0].id as string;
      const data = await readWorkspace(workspaceId);
      subscribe(workspaceId);
      lastCatchUp = Date.now();
      return data;
    },

    async save(next, previous) {
      const isNew = !previous || workspaceId !== next.workspace.id;
      if (isNew) {
        const { error } = await sb.from("workspaces").insert(workspaceRow(next.workspace));
        check(error, "Creating workspace");
        workspaceId = next.workspace.id;
        subscribe(workspaceId);
      } else if (previous.workspace !== next.workspace) {
        const { error } = await sb.from("workspaces").update(workspaceRow(next.workspace)).eq("id", workspaceId);
        check(error, "Saving workspace");
      }
      const wid = workspaceId!;

      for (const key of COLLECTION_KEYS) {
        const prev = isNew ? {} : previous?.[key] ?? {};
        const changed = Object.values(next[key]).filter((r) => prev[r.id] !== r);
        for (let i = 0; i < changed.length; i += 500) {
          const { error } = await sb.from(TABLES[key]).upsert(changed.slice(i, i + 500).map((r) => toRow(r, wid)), { defaultToNull: false });
          check(error, `Saving ${key}`);
        }
      }
      if (!isNew && previous) {
        for (const key of COLLECTION_KEYS) {
          const removed = Object.keys(previous[key]).filter((id) => !next[key][id]);
          for (let i = 0; i < removed.length; i += 200) {
            const { error } = await sb.from(TABLES[key]).delete().eq("workspace_id", wid).in("id", removed.slice(i, i + 200));
            check(error, `Deleting ${key}`);
          }
        }
      }
      const known = new Set(isNew ? [] : (previous?.activity ?? []).map((a) => a.id));
      const fresh = next.activity.filter((a) => !known.has(a.id));
      if (fresh.length) {
        const { error } = await sb.from("activity_log").upsert(fresh.map((a) => toRow(a, wid)), { defaultToNull: false });
        check(error, "Saving activity");
      }
      if (isNew) {
        const { data: ws } = await sb.from("workspaces").select("*").eq("id", wid).single();
        if (ws) emit({ kind: "workspace", workspace: fromRow(ws) as unknown as Workspace });
      }
    },

    async clear() {
      if (!workspaceId) return;
      const { error } = await sb.from("workspaces").delete().eq("id", workspaceId);
      check(error, "Deleting workspace");
      workspaceId = null;
    },

    onRemoteChange(cb) {
      listeners.add(cb);
      return () => listeners.delete(cb);
    },

  };
  return adapter;
}
