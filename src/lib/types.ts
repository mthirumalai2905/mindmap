/* ---------- Workspace ---------- */

export interface Workspace {
  id: ID;
  name: string;
  statusLabels: Record<Status, string>;
  /** When on, structural map changes re-run the tidy layout. */
  mapAutoLayout: boolean;
  /** Supabase only: code teammates use to join. Generated by the database. */
  joinCode?: string;
  createdBy?: string | null;
  createdAt: string;
  updatedAt: string;
}

interface BaseRecord {
  id: ID;
  createdAt: string;
  updatedAt: string;
  /** Seed/sample data. Shown with an "Example" label until edited away. */
  isExample?: boolean;
}

export interface Product extends BaseRecord {
  slug: string;
  name: string;
  kind: "product" | "initiative";
  url: string;
  tagline: string;
  description: string;
  positioning: string;
  audience: string;
  goals: string[];
  researchQuestions: string[];
  order: number;
}

export interface Category extends BaseRecord {
  productId: ID;
  name: string;
  description: string;
  order: number;
}

