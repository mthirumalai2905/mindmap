/* ---------- Relationships & activity ---------- */

export interface Link extends BaseRecord {
  aType: CollectionKey;
  aId: ID;
  bType: CollectionKey;
  bId: ID;
  label: string;
}

export interface ActivityEntry {
  id: ID;
  at: string;
  action: "created" | "updated" | "deleted" | "initialized";
  collection: CollectionKey | "workspace";
  entityId: ID;
  title: string;
}

export interface Collections {
  products: Product;
  categories: Category;
  nodes: MapNode;
  edges: MapEdge;
  content: ContentItem;
  initiatives: Initiative;
  research: ResearchIdea;
  tasks: Task;
  characters: Character;
  arcs: StoryArc;
  issues: ComicIssue;
  lore: LoreEntry;
  links: Link;
}
export type CollectionKey = keyof Collections;
export const COLLECTION_KEYS: CollectionKey[] = [
  "products",
  "categories",
  "nodes",
  "edges",
  "content",
  "initiatives",
  "research",
  "tasks",
  "characters",
  "arcs",
  "issues",
  "lore",
  "links",
];

export type CollectionMaps = { [K in CollectionKey]: Record<ID, Collections[K]> };

export interface WorkspaceData extends CollectionMaps {
  version: 1;
  workspace: Workspace;
  activity: ActivityEntry[];
}

export interface RecordRef {
  collection: CollectionKey;
  id: ID;
}
